import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const DIST=path.join(ROOT,'dist');
const load=async name=>readFile(path.join(DIST,name),'utf8');
const parseArray=async(name,variable)=>vm.runInNewContext((await load(name))+`;${variable}`);
const waite=await parseArray('waite-meanings.js','WAITE_MEANINGS');
const plain=await parseArray('plain-meanings.js','PLAIN_MEANINGS');
const yijing=await parseArray('yijing-text.js','YIJING_TEXT');
const experience=await load('experiences.js');
const start=experience.indexOf('const TRIGRAMS=');
const end=experience.indexOf('function castHexagram(');
if(start<0||end<=start)throw new Error('Hexagram mapping unavailable');
const hexSource=experience.slice(start,end);
const namesWithin=(source,begin,finish)=>{
  const start=source.indexOf(begin),end=source.indexOf(finish,start);
  if(start<0||end<0)throw new Error(`Card names unavailable: ${begin}`);
  return [...source.slice(start,end).matchAll(/^\s*\['([^']+)'/gm)].map(match=>match[1]);
};
const major=await load('app.js'),minor=await load('minor-cards.js');
const names=[...namesWithin(major,'const MAJOR_CARDS = [','].map((row'),...namesWithin(minor,'const MINOR_ROWS = {','const SUIT_META')];
if(waite.length!==78||plain.length!==78||names.length!==78||yijing.length!==64)throw new Error('Incomplete card or hexagram data');
const output=`// Generated by scripts/build-pages-data.mjs. Do not edit.\nconst YIJING_TEXT=${JSON.stringify(yijing)};\nexport const waite=${JSON.stringify(waite)};\nexport const plain=${JSON.stringify(plain)};\nexport const names=${JSON.stringify(names)};\n${hexSource}\nexport {hexagram};\n`;
await writeFile(path.join(ROOT,'pages-data.mjs'),output,'utf8');
console.log(`Built Pages data: ${names.length} Tarot cards, ${yijing.length} hexagrams`);
